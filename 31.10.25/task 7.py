print("To print weekdays")
week=int(input("Enter a number within 7 to view the day of the week"))
if week==1:
    print("Sunday")
elif week==2:
    print("Monday")
elif week==3:
    print("Tuesday")
elif week==4:
    print("Wednesday")
elif week==5:
    print("Thursday")
elif week==6:
    print("Friday")
elif week==7:
    print("Saturday")
else:
    print("Not in range")
